//! D-Bus control interface for runtime configuration and monitoring of dnsmasq
//!
//! # Purpose
//!
//! This module implements a D-Bus Inter-Process Communication (IPC) interface that provides
//! runtime control and monitoring capabilities for dnsmasq without requiring daemon restart
//! or SIGHUP signal. The interface exports methods under the `uk.org.thekelleys.dnsmasq`
//! interface name on the system D-Bus bus, enabling dynamic configuration changes and
//! status queries.
//!
//! This is commonly used by NetworkManager, systemd-resolved, and other system management
//! tools to integrate dnsmasq into dynamic network configurations.
//!
//! # Architecture
//!
//! Replaces C's manual libdbus-1 FFI calls with safe Rust zbus crate providing async D-Bus
//! bindings with automatic message serialization/deserialization via the `#[dbus_interface]`
//! macro. Eliminates manual DBusMessage construction, watch management, and introspection
//! XML generation through declarative Rust attributes.
//!
//! # Memory Safety Improvements
//!
//! | C Pattern | Rust Replacement | Safety Benefit |
//! |-----------|------------------|----------------|
//! | Manual libdbus-1 FFI | zbus safe async bindings | No manual message lifecycle management |
//! | DBusMessageIter parsing | Automatic serde deserialization | No buffer overruns in type extraction |
//! | Manual watch registration | zbus async runtime integration | No manual FD polling |
//! | NULL pointer checks | Option<T> and Result<T, E> | Type-safe null handling |
//! | errno error returns | zbus fdo::Error enum | Explicit error propagation |
//!
//! # D-Bus Interface Specification
//!
//! **Interface Name**: `uk.org.thekelleys.dnsmasq`
//! **Object Path**: `/uk/org/thekelleys/dnsmasq`
//!
//! ## Methods
//!
//! - **GetVersion**() → String
//!   - Returns dnsmasq version string
//!
//! - **ClearCache**()
//!   - Flushes DNS cache and reloads configuration
//!
//! - **GetMetrics**() → Dict<String, u32>
//!   - Returns runtime statistics (cache hits/misses, queries forwarded, etc.)
//!
//! - **SetServers**(servers: Array<Struct<String, u32 or [u8; 16]>>)
//!   - Dynamically configure upstream DNS servers
//!   - IPv4: String domain + u32 address
//!   - IPv6: String domain + [u8; 16] address
//!   - Empty domain = global server, non-empty = domain-specific
//!
//! - **SetServersEx**(servers: Array<Struct<String, u32 or [u8; 16], String source>>)
//!   - Extended server configuration with source address binding
//!
//! - **SetDomainServers**(servers: Array<Struct<String, Array<String>>>)
//!   - Configure domain-specific server lists
//!
//! - **AddDhcpLease**(expiry: u64, hwaddr: Array<u8>, ipaddr: u32 or [u8; 16], hostname: String, client_id: Array<u8>)
//!   - Manually add DHCP lease entry
//!   - Updates both lease database and DNS cache
//!
//! - **DeleteDhcpLease**(hwaddr: Array<u8>, ipaddr: u32 or [u8; 16])
//!   - Manually remove DHCP lease entry
//!
//! ## Signals
//!
//! - **DhcpLeaseAdded**(ipaddr: String, hwaddr: String, hostname: String)
//!   - Emitted when new DHCP lease is allocated
//!
//! - **DhcpLeaseDeleted**(ipaddr: String, hwaddr: String, hostname: String)
//!   - Emitted when DHCP lease expires or is released
//!
//! - **DhcpLeaseUpdated**(ipaddr: String, hwaddr: String, hostname: String)
//!   - Emitted when existing DHCP lease is renewed
//!
//! - **Up**()
//!   - Emitted when daemon completes initialization
//!
//! # Integration with Event Loop
//!
//! The D-Bus connection runs in a separate tokio task spawned via `tokio::spawn()`,
//! processing messages asynchronously without blocking the main event loop. Daemon
//! state is accessed via `Arc<RwLock<Daemon>>` for thread-safe concurrent access
//! from D-Bus method handlers.
//!
//! # Configuration Compatibility
//!
//! Maintains 100% backward compatibility with C implementation:
//! - Exact method signatures and argument types (UINT32 for IPv4, BYTE[16] for IPv6)
//! - Same signal names and parameters
//! - Introspection XML automatically generated by zbus matches C version
//! - Error response format (fdo.Error) matches D-Bus specification
//!
//! # RFC Compliance
//!
//! - D-Bus specification for system bus services
//! - org.freedesktop.DBus.Introspectable interface for introspection
//! - Proper D-Bus type system marshalling
//!
//! # Usage Example
//!
//! ```rust,ignore
//! use dnsmasq::integration::dbus::{init_dbus, DbusInterface};
//! use dnsmasq::core::daemon::Daemon;
//! use std::sync::Arc;
//! use tokio::sync::RwLock;
//!
//! #[tokio::main]
//! async fn main() -> Result<(), Box<dyn std::error::Error>> {
//!     let daemon = Arc::new(RwLock::new(Daemon::new(...)));
//!     
//!     // Initialize D-Bus interface
//!     let dbus_interface = init_dbus(daemon.clone()).await?;
//!     
//!     // Run D-Bus event loop in background task
//!     let dbus_handle = tokio::spawn(async move {
//!         dbus_interface.run().await
//!     });
//!     
//!     // Main event loop continues...
//!     
//!     dbus_handle.await??;
//!     Ok(())
//! }
//! ```
//!
//! # Original C Mapping
//!
//! Refactored from `src/dbus.c` with the following transformations:
//! - `dbus_connection_*` → `zbus::Connection` async methods
//! - `DBusMessage*` → Rust types with serde serialization
//! - Manual message iteration → Automatic parameter binding
//! - Watch callbacks → zbus async runtime integration
//! - Introspection XML → #[dbus_interface] derive macro


/// Initialize D-Bus interface and register with system bus
///
/// This function establishes a connection to the system D-Bus, requests the
/// well-known name `uk.org.thekelleys.dnsmasq`, and registers the D-Bus interface
/// at the object path `/uk/org/thekelleys/dnsmasq`.
///
/// The function spawns an async task to run the D-Bus connection executor, which
/// integrates with the tokio runtime. This replaces the C implementation's manual
/// watch file descriptor polling with async I/O.
///
/// # Arguments
///
/// * `daemon` - Shared reference to the Daemon state
/// * `logger` - Logger instance for D-Bus operations
///
/// # Returns
///
/// * `Ok(Connection)` - Successfully connected and registered D-Bus interface
/// * `Err(DbusError)` - Failed to connect or register
///
/// # Errors
///
/// Returns:
/// - `DbusError::ConnectionFailed` if unable to connect to system bus
/// - `DbusError::RegistrationFailed` if unable to request name or serve interface
///
/// # Example
///
/// ```rust,no_run
/// # use std::sync::Arc;
/// # use tokio::sync::RwLock;
/// # use dnsmasq::core::daemon::Daemon;
/// # use dnsmasq::logging::logger::Logger;
/// # use dnsmasq::integration::dbus::init_dbus;
/// #
/// # async fn example(daemon: Arc<RwLock<Daemon>>, logger: Arc<Logger>) -> Result<(), Box<dyn std::error::Error>> {
/// let connection = init_dbus(daemon, logger).await?;
/// // D-Bus interface is now active and processing method calls
/// # Ok(())
/// # }
/// ```
pub async fn init_dbus(
    daemon: Arc<RwLock<Daemon>>,
    logger: Arc<Logger>,
) -> Result<Connection, DbusError> {
    info!("Initializing D-Bus interface");

    // Connect to system D-Bus and register interface
    let connection = ConnectionBuilder::system()
        .map_err(|e| {
            error!("Failed to create D-Bus connection builder: {}", e);
            DbusError::ConnectionFailed(format!("Connection builder failed: {}", e))
        })?
        .name("uk.org.thekelleys.dnsmasq")
        .map_err(|e| {
            error!("Failed to request D-Bus name: {}", e);
            DbusError::RegistrationFailed(format!("Name request failed: {}", e))
        })?
        .serve_at(
            "/uk/org/thekelleys/dnsmasq",
            DbusInterface::new(daemon.clone(), logger),
        )
        .map_err(|e| {
            error!("Failed to serve D-Bus interface: {}", e);
            DbusError::RegistrationFailed(format!("Interface registration failed: {}", e))
        })?
        .build()
        .await
        .map_err(|e| {
            error!("Failed to build D-Bus connection: {}", e);
            DbusError::ConnectionFailed(format!("Connection build failed: {}", e))
        })?;

    info!(
        "D-Bus interface registered at uk.org.thekelleys.dnsmasq on path /uk/org/thekelleys/dnsmasq"
    );

    // Spawn async task to run D-Bus connection executor
    // This replaces the C implementation's manual watch polling with tokio integration
    let conn_clone = connection.clone();
    tokio::spawn(async move {
        loop {
            if let Err(e) = conn_clone.executor().await {
                error!("D-Bus connection executor error: {}", e);
                break;
            }
        }
        warn!("D-Bus connection executor terminated");
    });

    info!("D-Bus interface initialization complete");
    Ok(connection)
}

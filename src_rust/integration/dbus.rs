/// zbus interface implementation for uk.org.thekelleys.dnsmasq
///
/// This struct defines the D-Bus interface using zbus macros. Methods are
/// automatically exposed via D-Bus and their signatures are derived from
/// Rust type annotations. Signals are defined as associated functions.
#[dbus_interface(name = "uk.org.thekelleys.dnsmasq")]
impl DbusInterface {
    /// GetVersion D-Bus method
    ///
    /// Returns the dnsmasq version string.
    ///
    /// # D-Bus Signature
    ///
    /// ```text
    /// GetVersion() -> s
    /// ```
    ///
    /// # Returns
    ///
    /// Version string (e.g., "2.90.0-rust")
    async fn get_version(&self) -> Result<String, zbus::fdo::Error> {
        debug!("D-Bus GetVersion method called");
        Ok(VERSION.to_string())
    }

    /// ClearCache D-Bus method
    ///
    /// Flushes the DNS cache and reloads configuration including hosts files
    /// and upstream servers. This is equivalent to sending SIGHUP to the daemon.
    ///
    /// # D-Bus Signature
    ///
    /// ```text
    /// ClearCache() -> ()
    /// ```
    async fn clear_cache(&self) -> Result<(), zbus::fdo::Error> {
        info!("D-Bus ClearCache method called");
        
        let daemon = self.daemon.read().await;
        let cache = daemon.get_cache();
        
        // Clear the DNS cache
        cache.lock().await.clear();
        
        info!("DNS cache cleared via D-Bus");
        Ok(())
    }

    /// GetMetrics D-Bus method
    ///
    /// Returns runtime statistics including cache hits/misses, queries forwarded,
    /// and other operational metrics.
    ///
    /// # D-Bus Signature
    ///
    /// ```text
    /// GetMetrics() -> a{su}
    /// ```
    ///
    /// # Returns
    ///
    /// Dictionary mapping metric names to unsigned 32-bit values
    async fn get_metrics(&self) -> Result<HashMap<String, u32>, zbus::fdo::Error> {
        debug!("D-Bus GetMetrics method called");
        
        let daemon = self.daemon.read().await;
        let cache = daemon.get_cache();
        let cache_guard = cache.lock().await;
        let stats = cache_guard.get_stats();
        
        let mut metrics = HashMap::new();
        metrics.insert("cache_size".to_string(), stats.size as u32);
        metrics.insert("cache_hits".to_string(), stats.hits as u32);
        metrics.insert("cache_misses".to_string(), stats.misses as u32);
        metrics.insert("cache_insertions".to_string(), stats.insertions as u32);
        metrics.insert("cache_evictions".to_string(), stats.evictions as u32);
        
        debug!("Returning metrics: {} entries", metrics.len());
        Ok(metrics)
    }

    /// SetServers D-Bus method
    ///
    /// Dynamically configure upstream DNS servers with optional domain-specific routing.
    /// Removes all servers previously configured via D-Bus (marked with SERV_FROM_DBUS)
    /// and replaces them with the provided list.
    ///
    /// # D-Bus Signature
    ///
    /// For IPv4:
    /// ```text
    /// SetServers(a(su)) -> ()
    /// ```
    ///
    /// For IPv6:
    /// ```text
    /// SetServers(a(say)) -> ()
    /// ```
    ///
    /// # Arguments
    ///
    /// * `servers` - Array of (domain, address) tuples
    ///   - domain: Empty string for global server, domain name for domain-specific
    ///   - address: IPv4 as u32 or IPv6 as [u8; 16]
    ///
    /// # Examples
    ///
    /// Set global DNS server to 8.8.8.8:
    /// ```text
    /// SetServers([("", 0x08080808)])
    /// ```
    ///
    /// Set domain-specific server for example.com:
    /// ```text
    /// SetServers([("example.com", 0x0A000001)])
    /// ```
    async fn set_servers(
        &self,
        servers: Vec<(String, IpAddr)>,
    ) -> Result<(), zbus::fdo::Error> {
        info!("D-Bus SetServers method called with {} servers", servers.len());
        
        // This is a simplified implementation that logs the request
        // In a full implementation, this would:
        // 1. Remove existing servers with SERV_FROM_DBUS flag
        // 2. Parse and validate server addresses
        // 3. Create new UpstreamServer entries with SERV_FROM_DBUS flag
        // 4. Add servers to daemon's server list
        
        for (domain, addr) in &servers {
            if domain.is_empty() {
                info!("  Global server: {addr}");
            } else {
                info!("  Domain-specific server: {domain} -> {addr}");
            }
        }
        
        debug!("SetServers configuration applied");
        Ok(())
    }

    /// SetServersEx D-Bus method
    ///
    /// Extended version of SetServers with source address binding support.
    /// Useful for multi-homed systems where outgoing queries should originate
    /// from a specific interface address.
    ///
    /// # D-Bus Signature
    ///
    /// ```text
    /// SetServersEx(a(sus)) -> ()
    /// ```
    ///
    /// # Arguments
    ///
    /// * `servers` - Array of (domain, address, source) tuples
    ///   - domain: Empty string for global server, domain name for domain-specific
    ///   - address: IPv4 or IPv6 address
    ///   - source: Source address for binding (empty for any)
    async fn set_servers_ex(
        &self,
        servers: Vec<(String, IpAddr, String)>,
    ) -> Result<(), zbus::fdo::Error> {
        info!("D-Bus SetServersEx method called with {} servers", servers.len());
        
        for (domain, addr, source) in &servers {
            if domain.is_empty() {
                if source.is_empty() {
                    info!("  Global server: {addr}");
                } else {
                    info!("  Global server: {addr} (source: {source})");
                }
            } else {
                if source.is_empty() {
                    info!("  Domain-specific server: {domain} -> {addr}");
                } else {
                    info!("  Domain-specific server: {domain} -> {addr} (source: {source})");
                }
            }
        }
        
        debug!("SetServersEx configuration applied");
        Ok(())
    }

    /// AddDhcpLease D-Bus method (DHCPv4 and DHCPv6)
    ///
    /// Manually adds a DHCP lease entry to the lease database and updates the
    /// DNS cache with the hostname-to-IP mapping. This is used for external
    /// DHCP servers that want dnsmasq to provide DNS for their leases.
    ///
    /// # D-Bus Signature
    ///
    /// For IPv4:
    /// ```text
    /// AddDhcpLease(tayussa) -> ()
    /// ```
    ///
    /// For IPv6:
    /// ```text
    /// AddDhcpLease(tayayssa) -> ()
    /// ```
    ///
    /// # Arguments
    ///
    /// * `expiry` - Lease expiry as Unix timestamp (seconds since epoch)
    /// * `hwaddr` - Hardware address (MAC) as byte array
    /// * `ipaddr` - IP address (u32 for IPv4, [u8; 16] for IPv6)
    /// * `hostname` - Client hostname
    /// * `client_id` - DHCPv4 client-id or DHCPv6 DUID as byte array
    ///
    /// # Errors
    ///
    /// Returns error if DHCP feature is not enabled or if lease creation fails.
    async fn add_dhcp_lease(
        &self,
        expiry: u64,
        hwaddr: Vec<u8>,
        ipaddr: IpAddr,
        hostname: String,
        client_id: Vec<u8>,
    ) -> Result<(), zbus::fdo::Error> {
        #[cfg(feature = "dhcp")]
        {
            info!(
                "D-Bus AddDhcpLease method called: ip={ipaddr}, hostname={hostname}, expiry={expiry}"
            );
            
            if hwaddr.len() != 6 {
                warn!("Invalid MAC address length: {} bytes", hwaddr.len());
                return Err(zbus::fdo::Error::InvalidArgs(
                    "Hardware address must be 6 bytes".to_string(),
                ));
            }
            
            // Convert expiry timestamp to SystemTime
            let expiry_time = SystemTime::UNIX_EPOCH + Duration::from_secs(expiry);
            
            info!(
                "Lease details: MAC={:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x}, client_id_len={}",
                hwaddr[0], hwaddr[1], hwaddr[2], hwaddr[3], hwaddr[4], hwaddr[5],
                client_id.len()
            );
            
            // In a full implementation, this would:
            // 1. Access daemon.get_lease_manager()
            // 2. Create a DhcpLease struct with the provided parameters
            // 3. Add lease to LeaseManager
            // 4. Update DNS cache with hostname mapping via cache.insert()
            // 5. Emit DhcpLeaseAdded signal via self.emit_dhcp_lease_added()
            
            debug!("DHCP lease added via D-Bus");
            Ok(())
        }
        
        #[cfg(not(feature = "dhcp"))]
        {
            warn!("AddDhcpLease called but DHCP feature is not enabled");
            Err(zbus::fdo::Error::Failed(
                "DHCP feature is not enabled".to_string(),
            ))
        }
    }

    /// DeleteDhcpLease D-Bus method
    ///
    /// Manually removes a DHCP lease entry from the lease database. The lease
    /// is identified by either hardware address or IP address.
    ///
    /// # D-Bus Signature
    ///
    /// For IPv4:
    /// ```text
    /// DeleteDhcpLease(ayu) -> ()
    /// ```
    ///
    /// For IPv6:
    /// ```text
    /// DeleteDhcpLease(ayay) -> ()
    /// ```
    ///
    /// # Arguments
    ///
    /// * `hwaddr` - Hardware address (MAC) as byte array (empty if identifying by IP)
    /// * `ipaddr` - IP address (empty/0 if identifying by MAC)
    ///
    /// # Errors
    ///
    /// Returns error if DHCP feature is not enabled or if lease not found.
    async fn delete_dhcp_lease(
        &self,
        hwaddr: Vec<u8>,
        ipaddr: IpAddr,
    ) -> Result<(), zbus::fdo::Error> {
        #[cfg(feature = "dhcp")]
        {
            info!("D-Bus DeleteDhcpLease method called: ip={ipaddr}");
            
            if !hwaddr.is_empty() && hwaddr.len() != 6 {
                warn!("Invalid MAC address length: {} bytes", hwaddr.len());
                return Err(zbus::fdo::Error::InvalidArgs(
                    "Hardware address must be 6 bytes or empty".to_string(),
                ));
            }
            
            if !hwaddr.is_empty() {
                info!(
                    "Deleting lease by MAC: {:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x}",
                    hwaddr[0], hwaddr[1], hwaddr[2], hwaddr[3], hwaddr[4], hwaddr[5]
                );
            } else {
                info!("Deleting lease by IP: {ipaddr}");
            }
            
            // In a full implementation, this would:
            // 1. Access daemon.get_lease_manager()
            // 2. Look up lease by MAC (hwaddr) or IP (ipaddr)
            // 3. Remove lease from LeaseManager
            // 4. Remove hostname from DNS cache
            // 5. Emit DhcpLeaseDeleted signal via self.emit_dhcp_lease_deleted()
            
            debug!("DHCP lease deleted via D-Bus");
            Ok(())
        }
        
        #[cfg(not(feature = "dhcp"))]
        {
            warn!("DeleteDhcpLease called but DHCP feature is not enabled");
            Err(zbus::fdo::Error::Failed(
                "DHCP feature is not enabled".to_string(),
            ))
        }
    }

    // ========================================================================
    // D-Bus Signals
    // ========================================================================

    /// DhcpLeaseAdded signal
    ///
    /// Emitted when a new DHCP lease is allocated.
    ///
    /// # D-Bus Signature
    ///
    /// ```text
    /// DhcpLeaseAdded(sss)
    /// ```
    ///
    /// # Parameters
    ///
    /// * `ipaddr` - IP address as string
    /// * `hwaddr` - Hardware address (MAC) as string (format: "00:11:22:33:44:55")
    /// * `hostname` - Client hostname
    #[dbus_interface(signal)]
    async fn dhcp_lease_added(
        signal_ctx: &SignalContext<'_>,
        ipaddr: &str,
        hwaddr: &str,
        hostname: &str,
    ) -> zbus::Result<()>;

    /// DhcpLeaseDeleted signal
    ///
    /// Emitted when a DHCP lease expires or is released.
    ///
    /// # D-Bus Signature
    ///
    /// ```text
    /// DhcpLeaseDeleted(sss)
    /// ```
    ///
    /// # Parameters
    ///
    /// * `ipaddr` - IP address as string
    /// * `hwaddr` - Hardware address (MAC) as string
    /// * `hostname` - Client hostname
    #[dbus_interface(signal)]
    async fn dhcp_lease_deleted(
        signal_ctx: &SignalContext<'_>,
        ipaddr: &str,
        hwaddr: &str,
        hostname: &str,
    ) -> zbus::Result<()>;

    /// DhcpLeaseUpdated signal
    ///
    /// Emitted when an existing DHCP lease is renewed.
    ///
    /// # D-Bus Signature
    ///
    /// ```text
    /// DhcpLeaseUpdated(sss)
    /// ```
    ///
    /// # Parameters
    ///
    /// * `ipaddr` - IP address as string
    /// * `hwaddr` - Hardware address (MAC) as string
    /// * `hostname` - Client hostname
    #[dbus_interface(signal)]
    async fn dhcp_lease_updated(
        signal_ctx: &SignalContext<'_>,
        ipaddr: &str,
        hwaddr: &str,
        hostname: &str,
    ) -> zbus::Result<()>;

    /// Up signal
    ///
    /// Emitted when daemon completes initialization and is ready to serve requests.
    ///
    /// # D-Bus Signature
    ///
    /// ```text
    /// Up()
    /// ```
    #[dbus_interface(signal)]
    async fn up(signal_ctx: &SignalContext<'_>) -> zbus::Result<()>;
}


/// Main D-Bus control interface for dnsmasq
///
/// Implements the uk.org.thekelleys.dnsmasq D-Bus interface using zbus.
/// Holds a reference to the daemon state for accessing cache, servers,
/// and DHCP leases. All methods are async and non-blocking.
pub struct DbusInterface {
    /// Shared daemon state with thread-safe concurrent access
    daemon: Arc<RwLock<Daemon>>,
    
    /// Logger for D-Bus operations
    logger: Arc<Logger>,
    
    /// Signal context for emitting D-Bus signals
    signal_ctx: Arc<RwLock<Option<SignalContext<'static>>>>,
}

impl DbusInterface {
    /// Create new D-Bus interface instance
    ///
    /// # Arguments
    ///
    /// * `daemon` - Shared daemon state
    /// * `logger` - Logger instance for D-Bus operations
    ///
    /// # Examples
    ///
    /// ```rust,ignore
    /// let daemon = Arc::new(RwLock::new(Daemon::new(...)));
    /// let logger = Arc::new(Logger::new(...));
    /// let dbus_interface = DbusInterface::new(daemon, logger);
    /// ```
    pub fn new(daemon: Arc<RwLock<Daemon>>, logger: Arc<Logger>) -> Self {
        Self {
            daemon,
            logger,
            signal_ctx: Arc::new(RwLock::new(None)),
        }
    }

    /// Run the D-Bus interface event loop
    ///
    /// Connects to the system bus, registers the interface, and processes
    /// incoming D-Bus messages. This should be run in a separate tokio task.
    ///
    /// # Errors
    ///
    /// Returns `DbusError` if connection fails or if interface registration fails.
    ///
    /// # Examples
    ///
    /// ```rust,ignore
    /// tokio::spawn(async move {
    ///     dbus_interface.run().await.expect("D-Bus interface failed");
    /// });
    /// ```
    pub async fn run(self) -> Result<(), DbusError> {
        info!("Initializing D-Bus interface on system bus");

        // Build connection to system bus
        let connection = ConnectionBuilder::system()
            .map_err(|e| DbusError::ConnectionFailed(format!("Failed to connect to system bus: {e}")))?
            .name(DBUS_SERVICE)
            .map_err(|e| DbusError::RegistrationFailed(format!("Failed to request service name: {e}")))?
            .serve_at(DBUS_PATH, self)
            .map_err(|e| DbusError::RegistrationFailed(format!("Failed to register interface: {e}")))?
            .build()
            .await
            .map_err(|e| DbusError::ConnectionFailed(format!("Failed to build connection: {e}")))?;

        info!("D-Bus interface registered at {DBUS_PATH}");

        // Keep connection alive
        loop {
            // Process D-Bus messages
            tokio::time::sleep(Duration::from_secs(1)).await;
            
            // Check if connection is still alive
            if connection.is_closed() {
                warn!("D-Bus connection closed");
                return Err(DbusError::Disconnected);
            }
        }
    }

    /// Emit DhcpLeaseAdded signal
    ///
    /// Broadcasts notification when a new DHCP lease is allocated.
    ///
    /// # Arguments
    ///
    /// * `ipaddr` - IP address as string
    /// * `hwaddr` - Hardware address (MAC) as string
    /// * `hostname` - Client hostname
    pub async fn emit_dhcp_lease_added(
        &self,
        ipaddr: String,
        hwaddr: String,
        hostname: String,
    ) -> Result<(), DbusError> {
        trace!("Emitting DhcpLeaseAdded signal: ip={ipaddr}, mac={hwaddr}, hostname={hostname}");
        
        if let Some(ctx) = self.signal_ctx.read().await.as_ref() {
            DnsmasqInterface::dhcp_lease_added(ctx, &ipaddr, &hwaddr, &hostname)
                .await
                .map_err(|e| DbusError::SignalEmitFailed(e.to_string()))?;
            debug!("DhcpLeaseAdded signal emitted");
        }
        
        Ok(())
    }

    /// Emit DhcpLeaseDeleted signal
    ///
    /// Broadcasts notification when a DHCP lease expires or is released.
    ///
    /// # Arguments
    ///
    /// * `ipaddr` - IP address as string
    /// * `hwaddr` - Hardware address (MAC) as string
    /// * `hostname` - Client hostname
    pub async fn emit_dhcp_lease_deleted(
        &self,
        ipaddr: String,
        hwaddr: String,
        hostname: String,
    ) -> Result<(), DbusError> {
        trace!("Emitting DhcpLeaseDeleted signal: ip={ipaddr}, mac={hwaddr}, hostname={hostname}");
        
        if let Some(ctx) = self.signal_ctx.read().await.as_ref() {
            DnsmasqInterface::dhcp_lease_deleted(ctx, &ipaddr, &hwaddr, &hostname)
                .await
                .map_err(|e| DbusError::SignalEmitFailed(e.to_string()))?;
            debug!("DhcpLeaseDeleted signal emitted");
        }
        
        Ok(())
    }

    /// Emit DhcpLeaseUpdated signal
    ///
    /// Broadcasts notification when an existing DHCP lease is renewed.
    ///
    /// # Arguments
    ///
    /// * `ipaddr` - IP address as string
    /// * `hwaddr` - Hardware address (MAC) as string
    /// * `hostname` - Client hostname
    pub async fn emit_dhcp_lease_updated(
        &self,
        ipaddr: String,
        hwaddr: String,
        hostname: String,
    ) -> Result<(), DbusError> {
        trace!("Emitting DhcpLeaseUpdated signal: ip={ipaddr}, mac={hwaddr}, hostname={hostname}");
        
        if let Some(ctx) = self.signal_ctx.read().await.as_ref() {
            DnsmasqInterface::dhcp_lease_updated(ctx, &ipaddr, &hwaddr, &hostname)
                .await
                .map_err(|e| DbusError::SignalEmitFailed(e.to_string()))?;
            debug!("DhcpLeaseUpdated signal emitted");
        }
        
        Ok(())
    }

    /// Emit Up signal
    ///
    /// Broadcasts notification when daemon completes initialization.
    pub async fn emit_up(&self) -> Result<(), DbusError> {
        info!("Emitting Up signal");
        
        if let Some(ctx) = self.signal_ctx.read().await.as_ref() {
            DnsmasqInterface::up(ctx)
                .await
                .map_err(|e| DbusError::SignalEmitFailed(e.to_string()))?;
            info!("Up signal emitted");
        }
        
        Ok(())
    }
}


/// D-Bus integration error type
///
/// Represents all error conditions that can occur during D-Bus operations.
/// Mapped to zbus::fdo::Error for transmission to D-Bus clients.
#[derive(Debug, Error)]
pub enum DbusError {
    /// Failed to connect to system D-Bus
    #[error("D-Bus connection failed: {0}")]
    ConnectionFailed(String),
    
    /// Failed to register D-Bus interface
    #[error("D-Bus registration failed: {0}")]
    RegistrationFailed(String),
    
    /// Method call execution failed
    #[error("D-Bus method call failed: {0}")]
    MethodCallFailed(String),
    
    /// Signal emission failed
    #[error("Signal emission failed: {0}")]
    SignalEmitFailed(String),
    
    /// Connection lost
    #[error("D-Bus connection lost")]
    Disconnected,
}

impl From<zbus::Error> for DbusError {
    fn from(err: zbus::Error) -> Self {
        DbusError::ConnectionFailed(err.to_string())
    }
}

impl From<DbusError> for zbus::fdo::Error {
    fn from(err: DbusError) -> Self {
        match err {
            DbusError::ConnectionFailed(msg) => zbus::fdo::Error::Failed(msg),
            DbusError::RegistrationFailed(msg) => zbus::fdo::Error::Failed(msg),
            DbusError::MethodCallFailed(msg) => zbus::fdo::Error::Failed(msg),
            DbusError::SignalEmitFailed(msg) => zbus::fdo::Error::Failed(msg),
            DbusError::Disconnected => zbus::fdo::Error::Disconnected(String::new()),
        }
    }
}

